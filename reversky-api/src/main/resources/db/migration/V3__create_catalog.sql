CREATE TABLE rarities (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR(100) NOT NULL,
	deck_limit INTEGER NOT NULL,
	max_per_deck INTEGER,
	sorting_order INTEGER NOT NULL,

	CONSTRAINT uq_rarities_name UNIQUE (name),
	CONSTRAINT uq_rarities_sorting_order UNIQUE (sorting_order),
	CONSTRAINT chk_rarities_deck_limit CHECK (deck_limit >= 1),
	CONSTRAINT chk_rarities_max_per_deck CHECK (max_per_deck IS NULL OR max_per_deck >= 0)
);

CREATE TABLE factions (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR(100) NOT NULL,
	emblem_path TEXT NOT NULL,
	description TEXT,

	CONSTRAINT uq_factions_name UNIQUE (name)
);

CREATE TABLE faction_bonuses (
	origin_faction_id INTEGER NOT NULL REFERENCES factions (id),
	target_faction_id INTEGER NOT NULL REFERENCES factions (id),

	-- Può essere negativo: -1 è il malus contro la fazione che ti batte
	atk_bonus INTEGER NOT NULL DEFAULT 0,
	def_bonus INTEGER NOT NULL DEFAULT 0,

	PRIMARY KEY (origin_faction_id, target_faction_id),
	CONSTRAINT chk_faction_bonuses_no_self_matchup CHECK (origin_faction_id <> target_faction_id),
	CONSTRAINT chk_faction_bonuses_def_nonnegative CHECK (def_bonus >= 0)
);

CREATE INDEX idx_faction_bonuses_target_faction_id ON faction_bonuses (target_faction_id);

CREATE TABLE rule_sets (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	version VARCHAR(20) NOT NULL,
	is_active BOOLEAN NOT NULL DEFAULT FALSE,

	starting_life_points INTEGER NOT NULL,
	max_rounds INTEGER NOT NULL,

	deck_size INTEGER NOT NULL,
	deck_creatures INTEGER NOT NULL,
	deck_spells INTEGER NOT NULL,
	deck_hidden INTEGER NOT NULL,
	deck_items INTEGER NOT NULL,
	deck_terrains INTEGER NOT NULL,
	max_hidden_survival INTEGER NOT NULL,
	max_hidden_damage INTEGER NOT NULL,

	-- Vittoria e pareggio valgono solo per le partite RANKED
	signup_bonus INTEGER NOT NULL,
	win_reward INTEGER NOT NULL,
	draw_reward INTEGER NOT NULL,

	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	created_by_id INTEGER REFERENCES users (id),

	CONSTRAINT uq_rule_sets_version UNIQUE (version),
	CONSTRAINT chk_rule_sets_match CHECK (starting_life_points >= 1 AND max_rounds >= 1),
	CONSTRAINT chk_rule_sets_deck_parts CHECK (
		deck_creatures >= 1 AND deck_spells >= 0 AND deck_hidden >= 0 AND deck_items >= 0 AND deck_terrains >= 0
	),
	CONSTRAINT chk_rule_sets_deck_size CHECK (
		deck_creatures + deck_spells + deck_hidden + deck_items + deck_terrains = deck_size
	),
	CONSTRAINT chk_rule_sets_hidden CHECK (max_hidden_survival >= 0 AND max_hidden_damage >= 0),
	CONSTRAINT chk_rule_sets_credits CHECK (signup_bonus >= 0 AND win_reward >= 0 AND draw_reward >= 0)
);

-- Un solo rule set attivo alla volta
CREATE UNIQUE INDEX uq_rule_sets_one_active ON rule_sets (is_active) WHERE is_active;

CREATE TABLE tags (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR(100) NOT NULL,

	CONSTRAINT uq_tags_name UNIQUE (name),
	CONSTRAINT chk_tags_name_format CHECK (name ~ '^[A-Z0-9_]+$')
);

CREATE TABLE faction_tags (
	faction_id INTEGER NOT NULL REFERENCES factions (id),
	tag_id INTEGER NOT NULL REFERENCES tags (id),

	PRIMARY KEY (faction_id, tag_id)
);

CREATE INDEX idx_faction_tags_tag_id ON faction_tags (tag_id);

CREATE TABLE catalog_cards (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	rarity_id INTEGER NOT NULL REFERENCES rarities (id),
	-- Nulla solo per Spell e Hidden, che sono condivise tra le fazioni
	faction_id INTEGER REFERENCES factions (id),
	secondary_faction_id INTEGER REFERENCES factions (id),
	-- Versione evento di un'altra carta: stesse regole, altra grafica. Nullo = carta originale
	variant_of_id INTEGER REFERENCES catalog_cards (id),

	name VARCHAR(255) NOT NULL,
	type card_type NOT NULL,
	subtype card_subtype,
	effect_code VARCHAR(100),

	image_path TEXT NOT NULL,

	effect_description TEXT,
	flavor_text TEXT,

	atk INTEGER,
	def INTEGER,

	-- Se nullo prende il limite dalla rarità
	copy_limit INTEGER,

	is_active BOOLEAN NOT NULL DEFAULT TRUE,

	CONSTRAINT chk_catalog_cards_copy_limit CHECK (copy_limit IS NULL OR copy_limit >= 1),
	CONSTRAINT chk_catalog_cards_stats_match_type CHECK (
		(type = 'CREATURE' AND atk IS NOT NULL AND def IS NOT NULL AND atk >= 0 AND def >= 1)
		OR (type <> 'CREATURE' AND atk IS NULL AND def IS NULL)
	),
	CONSTRAINT chk_catalog_cards_faction_matches_type CHECK (
		(type IN ('SPELL', 'HIDDEN') AND faction_id IS NULL AND secondary_faction_id IS NULL)
		OR (type NOT IN ('SPELL', 'HIDDEN') AND faction_id IS NOT NULL)
	),
	CONSTRAINT chk_catalog_cards_distinct_factions CHECK (
		secondary_faction_id IS NULL OR (faction_id IS NOT NULL AND secondary_faction_id <> faction_id)
	),
	CONSTRAINT chk_catalog_cards_subtype_matches_type CHECK (
		(type = 'SPELL' AND subtype IS NOT NULL AND subtype IN ('DAMAGE', 'SHIELD', 'BURN'))
		OR (type = 'HIDDEN' AND subtype IS NOT NULL AND subtype IN ('SURVIVAL', 'DAMAGE'))
		OR (type IN ('CREATURE', 'TERRAIN', 'ITEM') AND subtype IS NULL)
	),
	CONSTRAINT chk_catalog_cards_effect_required CHECK (type = 'CREATURE' OR effect_code IS NOT NULL),
	CONSTRAINT chk_catalog_cards_not_own_variant CHECK (variant_of_id IS NULL OR variant_of_id <> id)
);

CREATE INDEX idx_catalog_cards_rarity_id ON catalog_cards (rarity_id);
CREATE INDEX idx_catalog_cards_faction_id ON catalog_cards (faction_id);
CREATE INDEX idx_catalog_cards_secondary_faction_id ON catalog_cards (secondary_faction_id);
CREATE INDEX idx_catalog_cards_variant_of_id ON catalog_cards (variant_of_id);
CREATE INDEX idx_catalog_cards_rarity_id_faction_id ON catalog_cards (rarity_id, faction_id);
CREATE INDEX idx_catalog_cards_is_active_rarity_id ON catalog_cards (is_active, rarity_id);
-- Nome univoco solo tra le carte originali: una variante può riusare quello della propria originale
CREATE UNIQUE INDEX uq_catalog_cards_base_name ON catalog_cards (name) WHERE variant_of_id IS NULL;

CREATE TABLE card_tags (
	card_id INTEGER NOT NULL REFERENCES catalog_cards (id),
	tag_id INTEGER NOT NULL REFERENCES tags (id),

	PRIMARY KEY (card_id, tag_id)
);

CREATE INDEX idx_card_tags_tag_id ON card_tags (tag_id);
