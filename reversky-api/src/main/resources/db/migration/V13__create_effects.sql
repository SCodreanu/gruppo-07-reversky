	code VARCHAR(100) PRIMARY KEY,
	applies_to card_type NOT NULL,

	-- Destinazione della chiave esterna composta di catalog_cards
	CONSTRAINT uq_effects_code_applies_to UNIQUE (code, applies_to)
);

