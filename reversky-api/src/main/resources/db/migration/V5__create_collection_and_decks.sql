-- Copie possedute: la riga si elimina quando l'utente non ha più copie della carta
CREATE TABLE collection_cards (
	user_id INTEGER NOT NULL REFERENCES users (id),
	card_id INTEGER NOT NULL REFERENCES catalog_cards (id),
	quantity INTEGER NOT NULL,

	PRIMARY KEY (user_id, card_id),
	CONSTRAINT chk_collection_cards_quantity_positive CHECK (quantity > 0)
);

CREATE INDEX idx_collection_cards_card_id ON collection_cards (card_id);

-- Composizione, possesso delle carte e limiti di copie sono controllati dal codice
CREATE TABLE decks (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id INTEGER NOT NULL REFERENCES users (id),
	name VARCHAR(50) NOT NULL,

	-- Copre anche le ricerche per user_id: nessun indice a parte
	CONSTRAINT uq_decks_user_id_name UNIQUE (user_id, name)
);

-- Si aggiorna riga per riga, mai svuotando e reinserendo (Hibernate esegue gli insert prima dei delete)
CREATE TABLE deck_cards (
	deck_id INTEGER NOT NULL REFERENCES decks (id) ON DELETE CASCADE,
	card_id INTEGER NOT NULL REFERENCES catalog_cards (id),
	quantity INTEGER NOT NULL,

	PRIMARY KEY (deck_id, card_id),
	CONSTRAINT chk_deck_cards_quantity_positive CHECK (quantity > 0)
);

CREATE INDEX idx_deck_cards_card_id ON deck_cards (card_id);
