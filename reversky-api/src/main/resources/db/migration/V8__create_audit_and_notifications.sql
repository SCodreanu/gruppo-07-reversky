-- Azioni e modifiche fatte dal backoffice. Le righe non si modificano e non si cancellano,
-- e non contengono mai password_hash o token.
CREATE TABLE audit_logs (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	admin_user_id INTEGER NOT NULL REFERENCES users (id),
	action VARCHAR(100) NOT NULL,
	entity_type VARCHAR(100) NOT NULL,
	-- Testo: le entità hanno chiavi intere, UUID o composte
	entity_id VARCHAR(100) NOT NULL,
	old_values JSONB,
	new_values JSONB,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_audit_logs_admin_user_id_created_at ON audit_logs (admin_user_id, created_at);
CREATE INDEX idx_audit_logs_entity_type_entity_id ON audit_logs (entity_type, entity_id);
CREATE INDEX idx_audit_logs_created_at ON audit_logs (created_at);

-- Notifiche degli utenti (amicizie, inviti, partite, scambi). Si salvano sempre e si inviano anche
-- sul canale SSE, dopo il commit della transazione che le crea.
CREATE TABLE notifications (
	-- Usato come id dell'evento SSE (Last-Event-ID)
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id INTEGER NOT NULL REFERENCES users (id),
	-- Testo e non enum (es. FRIEND_REQUEST_RECEIVED, BATTLE_COMPLETED): un nuovo tipo non richiede una migrazione
	type VARCHAR(50) NOT NULL,
	-- Id e username delle entità coinvolte, mai altri dati personali
	payload JSONB NOT NULL,
	-- Nullo = non letta
	read_at TIMESTAMPTZ,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Notifiche non lette
CREATE INDEX idx_notifications_user_id_read_at ON notifications (user_id, read_at);
-- Lista paginata e recupero degli eventi persi dopo Last-Event-ID
CREATE INDEX idx_notifications_user_id_id ON notifications (user_id, id);
