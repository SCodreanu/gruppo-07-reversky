-- Un inventario per utente. È anche il blocco di ogni spostamento di crediti, carte e pacchetti:
-- si blocca la riga di ogni utente coinvolto, in ordine di user_id crescente.
CREATE TABLE inventories (
	user_id INTEGER PRIMARY KEY REFERENCES users (id),
	credits INTEGER NOT NULL DEFAULT 0,

	CONSTRAINT chk_inventories_credits_nonnegative CHECK (credits >= 0)
);

-- Una riga per ogni modifica del saldo, nella stessa transazione. Le righe non si modificano e non si cancellano.
CREATE TABLE credit_transactions (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id INTEGER NOT NULL REFERENCES users (id),

	-- Positivo se guadagnati, negativo se spesi, 0 per un pacchetto gratuito
	amount INTEGER NOT NULL,
	reason credit_reason NOT NULL,

	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_credit_transactions_user_id_created_at ON credit_transactions (user_id, created_at);

CREATE TABLE packs (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR(255) NOT NULL,
	cost INTEGER NOT NULL,
	-- Massimo di pacchetti che un utente può comprare in totale. Nullo = nessun limite
	purchase_limit INTEGER,
	image_path TEXT NOT NULL,
	-- Nasce disattivato: si attiva solo quando i suoi slot base possono essere riempiti
	is_active BOOLEAN NOT NULL DEFAULT FALSE,

	CONSTRAINT uq_packs_name UNIQUE (name),
	CONSTRAINT chk_packs_cost_nonnegative CHECK (cost >= 0),
	CONSTRAINT chk_packs_purchase_limit CHECK (purchase_limit IS NULL OR purchase_limit >= 1),
	CONSTRAINT chk_packs_free_requires_limit CHECK (cost > 0 OR purchase_limit IS NOT NULL)
);

CREATE INDEX idx_packs_is_active ON packs (is_active);

-- Slot base: il numero di carte del pacchetto è la somma delle quantità
CREATE TABLE pack_rarity_rules (
	pack_id INTEGER NOT NULL REFERENCES packs (id),
	rarity_id INTEGER NOT NULL REFERENCES rarities (id),
	quantity INTEGER NOT NULL,

	PRIMARY KEY (pack_id, rarity_id),
	CONSTRAINT chk_pack_rarity_rules_quantity_positive CHECK (quantity > 0)
);

CREATE INDEX idx_pack_rarity_rules_rarity_id ON pack_rarity_rules (rarity_id);

-- Probabilità dei bonus in unità su 10.000 (1.000 = 10%): un bonus sostituisce uno slot base, non aggiunge carte
CREATE TABLE pack_bonus_rules (
	pack_id INTEGER NOT NULL REFERENCES packs (id),
	rarity_id INTEGER NOT NULL REFERENCES rarities (id),
	probability_units INTEGER NOT NULL,

	PRIMARY KEY (pack_id, rarity_id),
	CONSTRAINT chk_pack_bonus_rules_probability_range CHECK (probability_units >= 0 AND probability_units <= 10000)
);

CREATE INDEX idx_pack_bonus_rules_rarity_id ON pack_bonus_rules (rarity_id);

-- Filtro delle carte: un pacchetto senza righe accetta qualsiasi carta attiva, tranne le varianti
CREATE TABLE pack_tags (
	pack_id INTEGER NOT NULL REFERENCES packs (id),
	tag_id INTEGER NOT NULL REFERENCES tags (id),

	PRIMARY KEY (pack_id, tag_id)
);

CREATE INDEX idx_pack_tags_tag_id ON pack_tags (tag_id);

-- Pacchetti comprati e non ancora aperti: a quantità 0 la riga si elimina
CREATE TABLE pack_inventory (
	user_id INTEGER NOT NULL REFERENCES inventories (user_id),
	pack_id INTEGER NOT NULL REFERENCES packs (id),
	quantity INTEGER NOT NULL,

	PRIMARY KEY (user_id, pack_id),
	CONSTRAINT chk_pack_inventory_quantity_positive CHECK (quantity > 0)
);

CREATE INDEX idx_pack_inventory_pack_id ON pack_inventory (pack_id);

-- Storico delle aperture, scritto nella stessa transazione. Le righe non si modificano e non si cancellano.
CREATE TABLE pack_openings (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id INTEGER NOT NULL REFERENCES users (id),
	pack_id INTEGER NOT NULL REFERENCES packs (id),
	-- Carte ricevute, nell'ordine degli slot
	cards JSONB NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_pack_openings_user_id_created_at ON pack_openings (user_id, created_at);
CREATE INDEX idx_pack_openings_created_at ON pack_openings (created_at);
